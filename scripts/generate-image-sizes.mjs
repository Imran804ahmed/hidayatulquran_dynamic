// Generates src/generated/image-sizes.ts: intrinsic width/height of every image in public/assets/img.
// <SiteImage> uses it so pages can reference images by path without hard-coding dimensions.
// Run after adding or replacing images:  npm run images:sizes
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const imgDir = path.join(root, "public", "assets", "img");
const outFile = path.join(root, "src", "generated", "image-sizes.ts");

function pngSize(b) {
  return [b.readUInt32BE(16), b.readUInt32BE(20)];
}

function jpegSize(b) {
  let i = 2;
  while (i < b.length) {
    if (b[i] !== 0xff) { i++; continue; }
    const marker = b[i + 1];
    const len = b.readUInt16BE(i + 2);
    // SOF0..SOF15 except DHT (C4), JPG (C8), DAC (CC)
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return [b.readUInt16BE(i + 7), b.readUInt16BE(i + 5)];
    }
    i += 2 + len;
  }
  throw new Error("no SOF marker");
}

function svgSize(text) {
  const num = (attr) => Number.parseFloat(text.match(new RegExp(`<svg[^>]*\\s${attr}="([\\d.]+)`))?.[1] ?? "");
  let [w, h] = [num("width"), num("height")];
  if (!w || !h) {
    const vb = text.match(/viewBox="[\d.\s-]*?([\d.]+)\s+([\d.]+)"/);
    if (vb) [w, h] = [Number(vb[1]), Number(vb[2])];
  }
  if (!w || !h) throw new Error("no svg size");
  return [Math.round(w), Math.round(h)];
}

function sizeOf(file) {
  const b = fs.readFileSync(file);
  if (b.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return pngSize(b);
  if (b[0] === 0xff && b[1] === 0xd8) return jpegSize(b);
  if (file.endsWith(".svg")) return svgSize(b.toString("utf8"));
  throw new Error("unsupported format");
}

const entries = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(png|jpe?g|svg)$/i.test(e.name)) {
      const url = "/" + path.relative(path.join(root, "public"), p).split(path.sep).join("/");
      try {
        entries.push([url, sizeOf(p)]);
      } catch (err) {
        console.warn(`skipped ${url}: ${err.message}`);
      }
    }
  }
})(imgDir);

const body = entries.map(([url, [w, h]]) => `  ${JSON.stringify(url)}: [${w}, ${h}],`).join("\n");
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  `// Generated by scripts/generate-image-sizes.mjs — do not edit. Run \`npm run images:sizes\` after changing images.\n` +
    `export const IMAGE_SIZES: Record<string, readonly [width: number, height: number]> = {\n${body}\n};\n`,
);
console.log(`${entries.length} images -> ${path.relative(root, outFile)}`);
